"""Side-effect-free, per-session confirmation protocol for the VOXGATE web lab.

This module never executes an action. It only validates one-use approval of a
symbolic string already generated by a previously saved local model run.
"""
from __future__ import annotations

import hashlib
import hmac
import secrets
import time
from typing import Any

MAX_PENDING_SECONDS = 15 * 60


def transcript_fingerprint(transcript: str) -> str:
    if not isinstance(transcript, str) or not transcript.strip():
        raise ValueError("Transcript must be nonempty")
    return hashlib.sha256(transcript.encode("utf-8")).hexdigest()


def make_pending(*, case_id: str, policy: str, transcript: str,
                 action: str, allowed_actions: tuple[str, ...],
                 reason: str, was_held: bool, now: float | None = None) -> dict[str, Any]:
    """Build a session-serializable, short-lived exact-action proposal."""
    if not case_id or not policy or not isinstance(action, str) or action == "HOLD" or action not in allowed_actions:
        raise ValueError("Case, policy and allowlisted action are required")
    return {
        "token": secrets.token_urlsafe(24),
        "case_id": case_id,
        "policy": policy,
        "action": action,
        "fingerprint": transcript_fingerprint(transcript),
        "reason": reason,
        "was_held": bool(was_held),
        "created": time.time() if now is None else now,
    }


def confirm_pending(pending: dict[str, Any], *, token: str, action: str,
                    transcript: str, expected_action: str,
                    now: float | None = None) -> str:
    """Confirm a matching symbolic proposal; session owner MUST pop it first.

    Checking `expected_action` against the current saved model choice prevents
    confirmation of a stale proposal if the underlying report changed.
    """
    if not isinstance(pending, dict):
        raise ValueError("No pending proposal")
    required = {"token", "action", "fingerprint", "created", "case_id", "policy"}
    if not required.issubset(pending):
        raise ValueError("Incomplete pending proposal")
    created = pending["created"]
    current = time.time() if now is None else now
    if not isinstance(created, (int, float)) or current < created or current - created > MAX_PENDING_SECONDS:
        raise ValueError("Proposal expired")
    if (not isinstance(token, str) or not isinstance(action, str)
            or not hmac.compare_digest(token, pending["token"])
            or not hmac.compare_digest(action, pending["action"])
            or action != expected_action
            or not hmac.compare_digest(transcript_fingerprint(transcript), pending["fingerprint"])):
        raise ValueError("Proposal no longer matches the exact action and transcript")
    return action  # A symbolic approval string ONLY. No action is executed.
